#!/usr/bin/env node
/**
 * Generates config.js for Super Power (AWS AugmentAbility).
 * Run from this directory: node create-config.js
 * You need: Identity Pool ID, User Pool ID, User Pool Web Client ID, Region (e.g. ap-southeast-2).
 */

const fs = require('fs');
const path = require('path');

const readline = require('readline');
const rl = readline.createInterface({ input: process.stdin, output: process.stdout });

function ask(q) {
  return new Promise(resolve => rl.question(q, resolve));
}

async function main() {
  console.log('\nSuper Power config.js generator (Asia Pacific Sydney = ap-southeast-2)\n');

  const region = (await ask('AWS Region [ap-southeast-2]: ')).trim() || 'ap-southeast-2';
  const identityPoolId = (await ask('Identity Pool ID (from CloudFormation Outputs): ')).trim();
  const userPoolId = (await ask('User Pool ID (e.g. ap-southeast-2_XXXXXXXXX): ')).trim();
  const userPoolWebClientId = (await ask('User Pool Web Client ID: ')).trim();

  if (!identityPoolId || !userPoolId || !userPoolWebClientId) {
    console.error('Missing required values. Exiting.');
    rl.close();
    process.exit(1);
  }

  const domain = `${userPoolWebClientId}.auth.${region}.amazoncognito.com`;
  const port = (await ask('App port for redirect URLs [8000]: ')).trim() || '8000';
  const baseUrl = `http://localhost:${port}/aws-augmentability-main`;

  const config = `// Generated by create-config.js - Super Power (AWS AugmentAbility)
var amplifyConfig = {
  Auth: {
    region: '${region}',
    userPoolId: '${userPoolId}',
    userPoolWebClientId: '${userPoolWebClientId}',
    oauth: {
      domain: '${domain}',
      scope: ['email', 'openid'],
      redirectSignIn: '${baseUrl}/index-landing.html',
      redirectSignOut: '${baseUrl}/login.html',
      responseType: 'code'
    }
  }
};

var appConfig = {
  IdentityPoolId: '${identityPoolId}'
};
`;

  const outPath = path.join(__dirname, 'config.js');
  fs.writeFileSync(outPath, config, 'utf8');
  console.log('\nWrote config.js at:', outPath);
  console.log('Restart your app and use Super Power; sign in with Cognito when prompted.\n');
  rl.close();
}

main().catch(err => {
  console.error(err);
  rl.close();
  process.exit(1);
});
